//! Explicit, single-attempt login. Secrets have no Debug, Clone or Serialize path.
use crate::{screen::Frame, text};
use std::time::{Duration, Instant};
use zeroize::Zeroizing;

#[cfg(feature = "desktop")]
pub mod vault;

pub struct Credentials {
    pub account: String,
    password: Zeroizing<Vec<u8>>,
}
impl Credentials {
    pub fn new(account: String, password: Zeroizing<Vec<u8>>) -> Result<Self, String> {
        if !(2..=12).contains(&account.len())
            || !account.as_bytes()[0].is_ascii_alphabetic()
            || !account.bytes().all(|b| b.is_ascii_alphanumeric())
            || ["guest", "new", "register", "recover"]
                .contains(&account.to_ascii_lowercase().as_str())
        {
            return Err(crate::msg!("login-account-invalid"));
        }
        if !(1..=72).contains(&password.len()) || !password.iter().all(|b| (32..=126).contains(b)) {
            return Err(crate::msg!("login-password-invalid"));
        }
        Ok(Self { account, password })
    }
    pub fn account_input(&self) -> Zeroizing<Vec<u8>> {
        let mut bytes = Zeroizing::new(self.account.as_bytes().to_vec());
        bytes.push(b'\r');
        bytes
    }
    pub fn password_input(&self) -> Zeroizing<Vec<u8>> {
        let mut bytes = Zeroizing::new(self.password.to_vec());
        bytes.push(b'\r');
        bytes
    }
    #[cfg(all(feature = "desktop", target_os = "macos"))]
    fn stored(&self) -> Zeroizing<Vec<u8>> {
        let mut bytes = Zeroizing::new(self.account.as_bytes().to_vec());
        bytes.push(0);
        bytes.extend_from_slice(&self.password);
        bytes
    }
    #[cfg(all(feature = "desktop", target_os = "macos"))]
    fn from_stored(bytes: Zeroizing<Vec<u8>>) -> Result<Self, String> {
        let Some(separator) = bytes.iter().position(|b| *b == 0) else {
            return Err(crate::msg!("vault-record-invalid"));
        };
        let (account, password) = (&bytes[..separator], &bytes[separator + 1..]);
        let account =
            std::str::from_utf8(account).map_err(|_| crate::msg!("vault-account-invalid"))?;
        Self::new(account.to_owned(), Zeroizing::new(password.to_vec()))
    }
}

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Prompt {
    Account,
    Password,
}

/// Only the empty input at PTT's fixed login rows can receive credentials.
/// Text in an article, a partially typed input or an unfinished ANSI sequence cannot.
pub fn prompt(frame: &Frame) -> Option<Prompt> {
    let rows = login_rows(frame)?;
    let (col, row) = frame.cursor;
    let kind = match row {
        20 => Prompt::Account,
        21 => Prompt::Password,
        _ => return None,
    };
    let line = rows.get(row)?;
    if !line.mapped() || col == 0 || col >= 80 || !line.cells(col, 80)?.trim().is_empty() {
        return None;
    }
    let prefix = line.cells(0, col)?.trim();
    match kind {
        Prompt::Account if prefix == "請輸入代號，或以 guest 參觀，或以 new 註冊:" => {
            Some(kind)
        }
        Prompt::Password if matches!(prefix, "請輸入您的密碼:" | "請輸入您的密碼：") => {
            Some(kind)
        }
        _ => None,
    }
}

fn login_rows(frame: &Frame) -> Option<Vec<text::Row<'_>>> {
    if frame.cols != 80 || frame.rows != 24 || !frame.control_complete {
        return None;
    }
    if crate::navigation::analyze(frame).kind() != "unknown" {
        return None;
    }
    let rows = text::rows(frame)?;
    if ["主功能表", "看板列表", "我的最愛", "分類看板"]
        .iter()
        .any(|title| rows[0].bar_text(title))
        || rows[2].bar_text("作者")
    {
        return None;
    }
    Some(rows)
}

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum Guidance {
    #[default]
    Idle,
    Waiting,
    CodeRequired,
    CodeRejected,
    CheckingCode,
    Browsing,
    Manual,
    Expired,
}
impl Guidance {
    pub fn needs_input(self) -> bool {
        matches!(self, Self::CodeRequired | Self::CodeRejected)
    }
    pub fn active(self) -> bool {
        matches!(
            self,
            Self::Waiting | Self::CodeRequired | Self::CodeRejected | Self::CheckingCode
        )
    }
    pub fn message(self) -> Option<String> {
        Some(match self {
            Self::Idle => return None,
            Self::Waiting => crate::msg!("login-sent"),
            Self::CodeRequired => crate::msg!("login-code-required"),
            Self::CodeRejected => crate::msg!("login-code-rejected"),
            Self::CheckingCode => crate::msg!("login-code-checking"),
            Self::Browsing => crate::msg!("login-browsing"),
            Self::Manual => crate::msg!("login-manual-followup"),
            Self::Expired => crate::msg!("login-followup-expired"),
        })
    }
}

/// The empty challenge line, with either public logind/mbbsd spacing variant.
/// No code is extracted, returned, retained, or generated by this recognizer.
pub fn verification(frame: &Frame) -> Option<Guidance> {
    let rows = login_rows(frame)?;
    let (col, row) = frame.cursor;
    if row != 21
        || col == 0
        || col >= 80
        || !rows[21].mapped()
        || !rows[21].cells(col, 80)?.trim().is_empty()
    {
        return None;
    }
    let prefix: String = rows[21]
        .cells(0, col)?
        .chars()
        .filter(|c| !c.is_whitespace())
        .collect();
    if !matches!(
        prefix.as_str(),
        "請輸入兩階段(2FA)驗證碼(6位限時數字或8位救援碼):"
            | "請輸入兩階段(2FA)驗證碼(6位限時數字或8位救援碼)："
    ) {
        return None;
    }
    let rejected = [
        (20, "驗證碼錯誤！請確認後重新輸入。"),
        (22, "驗證碼錯誤。請確定在時限前輸入完畢。"),
    ]
    .iter()
    .any(|(row, message)| rows[*row].mapped() && rows[*row].text.trim() == *message);
    Some(if rejected {
        Guidance::CodeRejected
    } else {
        Guidance::CodeRequired
    })
}

pub const FOLLOWUP_LIMIT: Duration = Duration::from_secs(120);

/// Secret-free follow-up for one explicit password submission, owned by Session.
pub struct FollowUp {
    state: Guidance,
    observed_revision: u64,
    deadline: Instant,
}
impl FollowUp {
    pub fn after_password(revision: u64, now: Instant) -> Self {
        Self {
            state: Guidance::Waiting,
            observed_revision: revision,
            deadline: now + FOLLOWUP_LIMIT,
        }
    }
    pub fn observe(&mut self, frame: &Frame, now: Instant) -> Option<Guidance> {
        let next = if now >= self.deadline {
            Guidance::Expired
        } else {
            if !frame.control_complete || frame.revision <= self.observed_revision {
                return None;
            }
            self.observed_revision = frame.revision;
            if !matches!(
                crate::navigation::analyze(frame),
                crate::navigation::Context::Unknown { .. }
            ) {
                Guidance::Browsing
            } else if let Some(challenge) = verification(frame) {
                challenge
            } else if prompt(frame).is_some() {
                Guidance::Manual
            } else {
                return None;
            }
        };
        if next == self.state {
            return None;
        }
        self.state = next;
        Some(next)
    }
    pub fn submitted_code(&mut self, revision: u64) -> Option<Guidance> {
        if !self.state.needs_input() {
            return None;
        }
        self.observed_revision = revision;
        self.state = Guidance::CheckingCode;
        Some(self.state)
    }
}

/// The preceding row must echo the exact account from this login attempt.
pub fn password_prompt(frame: &Frame, account: &str) -> bool {
    if prompt(frame) != Some(Prompt::Password) {
        return false;
    }
    let Some(rows) = text::rows(frame) else {
        return false;
    };
    rows[20].mapped()
        && rows[20].text.trim() == format!("請輸入代號，或以 guest 參觀，或以 new 註冊: {account}")
}

#[cfg(all(test, feature = "desktop", target_os = "macos"))]
mod tests {
    use super::*;
    #[test]
    fn stored_secret_round_trip_and_invalid_store_are_explicit() {
        let original = Credentials::new(
            "StellaTest".into(),
            Zeroizing::new(b"synthetic+42".to_vec()),
        )
        .unwrap();
        let restored = Credentials::from_stored(original.stored()).unwrap();
        assert_eq!(restored.account, "StellaTest");
        assert_eq!(*restored.password_input(), b"synthetic+42\r");
        for bytes in [
            b"broken".as_slice(),
            b"guest\0abc",
            b"StellaTest\0abc\0def",
            b"StellaTest\0",
        ] {
            assert!(Credentials::from_stored(Zeroizing::new(bytes.to_vec())).is_err());
        }
    }
}
